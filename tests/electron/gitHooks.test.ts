// Commit Shield git hooks — install / uninstall / detect.
//
// The stakes here are asymmetric. Failing to install our hook costs a user one
// unscanned commit; DESTROYING their husky / lint-staged / pre-commit-framework
// hook costs them their whole CI contract, silently. So most of these tests are
// about what we must NOT do: never clobber a foreign hook, never leave a
// half-valid script behind on uninstall, never wedge git when Termpolis is gone.
//
// Everything is dependency-injected — no real filesystem, no real shell.
import { describe, it, expect, vi } from 'vitest'
import { join, posix, win32 } from 'path'
import {
  renderHook,
  installHooks,
  uninstallHooks,
  hookStatus,
  hookFileKind,
  unsafeHook,
  shieldNodePath,
  hooksPathScopes,
  shieldMayWriteHooks,
  shieldHooksAllowed,
  shieldHooksVerdict,
  type HooksWriteFacts,
  type HookDeps,
  type HookFileKind,
  type HookPaths,
} from '../../src/main/gitHooks'

const BEGIN = '# >>> termpolis commit shield >>>'
const END = '# <<< termpolis commit shield <<<'

/** An in-memory hooks dir. Records every write/chmod/remove so tests can assert
 *  on what was touched — and, just as importantly, on what was NOT. */
function fakeFs(seed: Record<string, string> = {}, kinds: Record<string, HookFileKind> = {}) {
  const files = new Map<string, string>(Object.entries(seed))
  const modes = new Map<string, number>()
  const removed: string[] = []
  const wrote: string[] = []
  const deps: HookDeps = {
    readFile: (p) => (files.has(p) ? (files.get(p) as string) : null),
    writeFile: (p, data) => { files.set(p, data); wrote.push(p) },
    exists: (p) => files.has(p),
    chmod: (p, mode) => { modes.set(p, mode) },
    remove: (p) => { files.delete(p); removed.push(p) },
    // What lstat would say: a seeded kind (a link, a pipe) first, else a regular file when seeded, else absent.
    fileKind: (p) => kinds[p] ?? (files.has(p) ? 'file' : 'absent'),
  }
  return { deps, files, modes, removed, wrote }
}

// Windows paths, with the space that breaks every naive hook generator.
const PATHS: HookPaths = {
  hooksDir: '/repo/.git/hooks',
  nodePath: 'C:\\Program Files\\nodejs\\node.exe',
  scriptPath: 'C:\\Program Files\\Termpolis\\resources\\mcp-adapter\\termpolis-githook.cjs',
}
const PRE_COMMIT = join(PATHS.hooksDir, 'pre-commit')
const PRE_PUSH = join(PATHS.hooksDir, 'pre-push')

// A textbook husky hook: bash shebang, a source line, a gating command.
const HUSKY = [
  '#!/usr/bin/env bash',
  '. "$(dirname -- "$0")/_/husky.sh"',
  '',
  'npx lint-staged || exit 1',
  'echo "lint ok"',
  '',
].join('\n')

// pre-commit.com generates a PYTHON hook. sh code injected into it is not a
// comment — it is a SyntaxError, i.e. a wedged repo.
const PYTHON_HOOK = [
  '#!/usr/bin/env python3',
  '# File generated by pre-commit: https://pre-commit.com',
  'import sys',
  'sys.exit(main())',
  '',
].join('\n')

const countOccurrences = (hay: string, needle: string) => hay.split(needle).length - 1

describe('renderHook — the script text', () => {
  it('is a POSIX sh script (Git for Windows runs hooks through sh)', () => {
    const out = renderHook('pre-commit', PATHS)
    expect(out.startsWith('#!/bin/sh\n')).toBe(true)
    // A stray CR turns every line into `command not found` under MSYS sh.
    expect(out).not.toContain('\r')
  })

  it('wraps our lines in the sentinel block', () => {
    const out = renderHook('pre-push', PATHS)
    expect(out).toContain(BEGIN)
    expect(out).toContain(END)
    expect(out.indexOf(BEGIN)).toBeLessThan(out.indexOf(END))
  })

  it('carries the node path, the scanner path, and the mode arg', () => {
    const posix: HookPaths = {
      hooksDir: '/repo/.git/hooks',
      nodePath: '/usr/local/bin/node',
      scriptPath: '/opt/Termpolis/resources/mcp-adapter/termpolis-githook.cjs',
    }
    const out = renderHook('pre-commit', posix)
    expect(out).toContain('/usr/local/bin/node')
    expect(out).toContain('/opt/Termpolis/resources/mcp-adapter/termpolis-githook.cjs')
    expect(out).toContain('pre-commit')
    expect(out).not.toContain('pre-push')
  })

  it('passes the hook name to the scanner as the mode arg', () => {
    expect(renderHook('pre-push', PATHS)).toMatch(/"\$_termpolis_shield" pre-push/)
    expect(renderHook('pre-commit', PATHS)).toMatch(/"\$_termpolis_shield" pre-commit/)
  })

  it('single-quotes paths that contain spaces', () => {
    const out = renderHook('pre-commit', PATHS)
    expect(out).toContain("'C:/Program Files/nodejs/node.exe'")
    expect(out).toContain("'C:/Program Files/Termpolis/resources/mcp-adapter/termpolis-githook.cjs'")
    // and every expansion of them is double-quoted at the point of use
    expect(out).not.toMatch(/\[ -x \$_termpolis_node \]/)
    expect(out).toContain('[ -x "$_termpolis_node" ]')
  })

  it('normalises Windows backslashes to forward slashes', () => {
    // MSYS sh treats a backslash path as interpreter-dependent at best; forward
    // slashes are accepted by Windows APIs and by every other platform.
    const out = renderHook('pre-commit', PATHS)
    expect(out).not.toContain('C:\\Program Files')
    expect(out).toContain('C:/Program Files')
  })

  it("escapes a single quote in a path (C:\\Users\\O'Brien)", () => {
    const out = renderHook('pre-commit', {
      ...PATHS,
      nodePath: "C:\\Users\\O'Brien\\node.exe",
    })
    expect(out).toContain("'C:/Users/O'\\''Brien/node.exe'")
  })

  it('FAILS OPEN when node is missing, and says so on stderr', () => {
    const out = renderHook('pre-commit', PATHS)
    expect(out).toContain('case "$_termpolis_node" in /*|[A-Za-z]:/*) [ -x "$_termpolis_node" ] ;; *) false ;; esac || {')
    expect(out).toContain('    echo "Termpolis Commit Shield skipped: node was not found at $_termpolis_node. Protect this repository again in Termpolis." >&2\n    return 0\n  }')
  })

  it('FAILS OPEN when the scanner is gone (Termpolis uninstalled)', () => {
    const out = renderHook('pre-push', PATHS)
    expect(out).toContain('[ -f "$_termpolis_shield" ] || return 0')
  })

  it('FAILS OPEN when node cannot be executed (126 / 127)', () => {
    const out = renderHook('pre-commit', PATHS)
    expect(out).toContain('-eq 126')
    expect(out).toContain('-eq 127')
  })

  it('never looks node up on PATH: only the full path it was installed with runs (M1)', () => {
    // The hook runs in the repository, and a PATH entry can name a folder inside it: a node planted there would run
    // as the scanner. A moved node skips the scan with a line on stderr instead (the FAILS OPEN test above).
    const out = renderHook('pre-commit', PATHS)
    expect(out).not.toContain('command -v')
    expect(out).not.toContain('which ')
    expect(out).not.toMatch(/_termpolis_node=\$\(/)
    const assigned = [...out.matchAll(/^\s*_termpolis_node=(.*)$/gm)].map((m) => m[1])
    expect(assigned).toEqual(["'C:/Program Files/nodejs/node.exe'"])
  })

  it("lets the SCANNER's exit code be what blocks the commit", () => {
    const out = renderHook('pre-commit', PATHS)
    expect(out).toContain('return "$_termpolis_code"')
    expect(out).toContain('termpolis_commit_shield || exit 1')
  })

  it('never exits 0 from inside the block (that would skip a chained hook)', () => {
    for (const line of renderHook('pre-commit', PATHS).split('\n')) {
      expect(line.trim()).not.toBe('exit 0')
    }
  })

  it('namespaces every variable it leaks into a chained script', () => {
    const out = renderHook('pre-commit', PATHS)
    // Our block runs in the SAME shell as any foreign hook below it. A bare
    // NODE= / code= would silently overwrite the user's variable.
    const assigned = [...out.matchAll(/^\s*([A-Za-z_][A-Za-z0-9_]*)=/gm)].map((m) => m[1])
    expect(assigned.length).toBeGreaterThan(0)
    for (const name of assigned) expect(name.startsWith('_termpolis_')).toBe(true)
  })

  it('leaves stdin alone (a chained pre-push still needs its ref list)', () => {
    // git feeds pre-push the refs being pushed on STDIN. If we redirected or
    // drained it, a husky pre-push chained below us would read EOF and pass
    // everything. Redirecting stderr is fine; stdin must stay untouched.
    const out = renderHook('pre-push', PATHS)
    expect(out).not.toContain('</dev/null')
    expect(out).not.toContain('< /dev/null')
    expect(out).not.toContain('| "$_termpolis_node"')
  })
})

describe('installHooks — empty hooks dir', () => {
  it('writes both hooks, executable', () => {
    const fs = fakeFs()
    const written = installHooks(PATHS, fs.deps)
    expect(written).toEqual(['pre-commit', 'pre-push'])
    expect(fs.files.get(PRE_COMMIT)).toBe(renderHook('pre-commit', PATHS))
    expect(fs.files.get(PRE_PUSH)).toBe(renderHook('pre-push', PATHS))
    expect(fs.modes.get(PRE_COMMIT)).toBe(0o755)
    expect(fs.modes.get(PRE_PUSH)).toBe(0o755)
  })

  it('is idempotent — installing twice is byte-identical, with ONE block', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    const first = fs.files.get(PRE_COMMIT) as string
    installHooks(PATHS, fs.deps)
    const second = fs.files.get(PRE_COMMIT) as string
    expect(second).toBe(first)
    expect(countOccurrences(second, BEGIN)).toBe(1)
    expect(countOccurrences(second, END)).toBe(1)
  })

  it('rewrites an in-place block when the node path moves (upgrade, not append)', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    const moved = { ...PATHS, nodePath: 'C:\\nvm\\v22\\node.exe' }
    installHooks(moved, fs.deps)
    const out = fs.files.get(PRE_COMMIT) as string
    expect(countOccurrences(out, BEGIN)).toBe(1)
    expect(out).toContain('C:/nvm/v22/node.exe')
    expect(out).not.toContain('C:/Program Files/nodejs/node.exe')
  })
})

describe('installHooks — a FOREIGN hook is already there', () => {
  it('preserves the husky hook and chains to it', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    const written = installHooks(PATHS, fs.deps)
    expect(written).toEqual(['pre-commit', 'pre-push'])
    const out = fs.files.get(PRE_COMMIT) as string

    // their shebang still owns the file (husky's bash-isms must keep bash)
    expect(out.startsWith('#!/usr/bin/env bash\n')).toBe(true)
    // their command survives...
    expect(out).toContain('npx lint-staged || exit 1')
    expect(out).toContain('. "$(dirname -- "$0")/_/husky.sh"')
    // ...and it still GATES: their body is the verbatim tail of the file, so
    // its exit code is the hook's exit code by fall-through.
    const foreignBody = HUSKY.slice(HUSKY.indexOf('\n') + 1)
    expect(out.endsWith(foreignBody)).toBe(true)
    // we run FIRST, then delegate: block sits between shebang and their code
    expect(out.indexOf(BEGIN)).toBeGreaterThan(0)
    expect(out.indexOf(END)).toBeGreaterThan(out.indexOf(BEGIN))
    expect(out.indexOf('npx lint-staged')).toBeGreaterThan(out.indexOf(END))
    expect(fs.modes.get(PRE_COMMIT)).toBe(0o755)
  })

  it('is idempotent when chained too', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    const first = fs.files.get(PRE_COMMIT) as string
    installHooks(PATHS, fs.deps)
    expect(fs.files.get(PRE_COMMIT)).toBe(first)
    expect(countOccurrences(first, BEGIN)).toBe(1)
    expect(countOccurrences(first, 'npx lint-staged')).toBe(1)
  })

  it('chains a hook that has no shebang at all', () => {
    const bare = 'make verify\n'
    const fs = fakeFs({ [PRE_PUSH]: bare })
    installHooks(PATHS, fs.deps)
    const out = fs.files.get(PRE_PUSH) as string
    expect(out.startsWith(BEGIN)).toBe(true)
    expect(out.endsWith(bare)).toBe(true)
  })

  it('does not rewrite the line endings of a CRLF hook', () => {
    const crlf = '#!/bin/sh\r\nnpm test\r\n'
    const fs = fakeFs({ [PRE_COMMIT]: crlf })
    installHooks(PATHS, fs.deps)
    const out = fs.files.get(PRE_COMMIT) as string
    expect(out).toContain('#!/bin/sh\r\n')
    expect(out).toContain('npm test\r\n')
    expect(out).toContain(BEGIN + '\n') // ...but OUR lines are always LF
  })

  it('REFUSES to overwrite a hook it cannot READ', () => {
    // EPERM, a binary file, a race. If we cannot read it we do not get to guess what
    // is in it — and writing over it is the exact clobber this module exists to stop.
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    const deps: HookDeps = { ...fs.deps, readFile: (p) => (p === PRE_COMMIT ? null : fs.deps.readFile(p)) }
    const written = installHooks(PATHS, deps)
    expect(written).toEqual(['pre-push'])
    expect(fs.wrote).not.toContain(PRE_COMMIT)
    expect(fs.files.get(PRE_COMMIT)).toBe(HUSKY)
  })

  it('REFUSES to inject sh into a non-shell hook (pre-commit.com python)', () => {
    const fs = fakeFs({ [PRE_COMMIT]: PYTHON_HOOK })
    const written = installHooks(PATHS, fs.deps)
    // pre-commit is skipped entirely rather than corrupted into a SyntaxError
    expect(written).toEqual(['pre-push'])
    expect(fs.files.get(PRE_COMMIT)).toBe(PYTHON_HOOK)
    expect(fs.wrote).not.toContain(PRE_COMMIT)
    expect(fs.modes.has(PRE_COMMIT)).toBe(false)
    // ...and the other hook still installs
    expect(fs.files.get(PRE_PUSH)).toBe(renderHook('pre-push', PATHS))
  })
})

describe('uninstallHooks', () => {
  it('deletes the file when the hook is ours alone', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    const cleaned = uninstallHooks(PATHS, fs.deps)
    expect(cleaned).toEqual(['pre-commit', 'pre-push'])
    expect(fs.removed).toEqual([PRE_COMMIT, PRE_PUSH])
    expect(fs.files.has(PRE_COMMIT)).toBe(false)
    expect(fs.files.has(PRE_PUSH)).toBe(false)
  })

  it('strips ONLY our block from a chained hook — byte-identical round trip', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    const cleaned = uninstallHooks(PATHS, fs.deps)
    expect(cleaned).toContain('pre-commit')
    expect(fs.files.get(PRE_COMMIT)).toBe(HUSKY) // exactly what they had
    expect(fs.removed).not.toContain(PRE_COMMIT) // their hook is NOT deleted
  })

  it('leaves the stripped hook valid and executable', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    uninstallHooks(PATHS, fs.deps)
    const out = fs.files.get(PRE_COMMIT) as string
    expect(out.startsWith('#!/usr/bin/env bash\n')).toBe(true)
    expect(out).not.toContain('termpolis')
    expect(out).toContain('npx lint-staged || exit 1')
    expect(fs.modes.get(PRE_COMMIT)).toBe(0o755)
  })

  it('never touches a hook that was never ours', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY, [PRE_PUSH]: PYTHON_HOOK })
    const cleaned = uninstallHooks(PATHS, fs.deps)
    expect(cleaned).toEqual([])
    expect(fs.removed).toEqual([])
    expect(fs.wrote).toEqual([])
    expect(fs.files.get(PRE_COMMIT)).toBe(HUSKY)
    expect(fs.files.get(PRE_PUSH)).toBe(PYTHON_HOOK)
  })

  it('is a no-op when there is nothing installed', () => {
    const fs = fakeFs()
    expect(uninstallHooks(PATHS, fs.deps)).toEqual([])
    expect(fs.removed).toEqual([])
  })

  it('leaves an unreadable hook alone', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    const deps: HookDeps = { ...fs.deps, readFile: () => null }
    expect(uninstallHooks(PATHS, deps)).toEqual([])
    expect(fs.removed).toEqual([])
    expect(fs.wrote).toEqual([])
    expect(fs.files.get(PRE_COMMIT)).toBe(HUSKY)
  })

  it('is idempotent', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    uninstallHooks(PATHS, fs.deps)
    expect(uninstallHooks(PATHS, fs.deps)).toEqual([])
    expect(fs.files.get(PRE_COMMIT)).toBe(HUSKY)
  })
})

// I1: every write follows a link, so a pre-commit that links to ~/.bashrc would get the shield block and an exec bit
// there. A link (symbolic, a junction, a hard link) or a file that is not a regular one is never read, written or
// removed; index.ts refuses the whole install over one (unsafeHook).
describe('Commit Shield hooks — a hook file that is a link (I1)', () => {
  it('install skips a linked hook and a hook that is not a regular file, and writes the other one', () => {
    for (const kind of ['link', 'other'] as const) {
      const fs = fakeFs({ [PRE_COMMIT]: 'echo target\n' }, { [PRE_COMMIT]: kind })
      expect(installHooks(PATHS, fs.deps)).toEqual(['pre-push'])
      expect(fs.files.get(PRE_COMMIT)).toBe('echo target\n')
      expect(fs.wrote).toEqual([PRE_PUSH])
      expect(fs.modes.has(PRE_COMMIT)).toBe(false)
    }
  })

  it('install never creates the target of a link that leads nowhere (a dangling link reads as absent to exists)', () => {
    const fs = fakeFs({}, { [PRE_COMMIT]: 'link' })
    expect(installHooks(PATHS, fs.deps)).toEqual(['pre-push'])
    expect(fs.files.has(PRE_COMMIT)).toBe(false)
  })

  it('uninstall leaves a linked hook that carries our block untouched', () => {
    const ours = renderHook('pre-commit', PATHS)
    for (const kind of ['link', 'other'] as const) {
      const fs = fakeFs({ [PRE_COMMIT]: ours, [PRE_PUSH]: renderHook('pre-push', PATHS) }, { [PRE_COMMIT]: kind })
      expect(uninstallHooks(PATHS, fs.deps)).toEqual(['pre-push'])
      expect(fs.files.get(PRE_COMMIT)).toBe(ours)
      expect(fs.removed).toEqual([PRE_PUSH])
      expect(fs.wrote).toEqual([])
    }
  })

  it('unsafeHook names the first hook that is a link or not a regular file, and null when there is none', () => {
    expect(unsafeHook(PATHS, fakeFs({ [PRE_COMMIT]: HUSKY }).deps)).toBeNull()
    expect(unsafeHook(PATHS, fakeFs({}, { [PRE_PUSH]: 'link' }).deps)).toEqual({ name: 'pre-push', kind: 'link' })
    expect(unsafeHook(PATHS, fakeFs({}, { [PRE_COMMIT]: 'other', [PRE_PUSH]: 'link' }).deps)).toEqual({ name: 'pre-commit', kind: 'other' })
  })

  it('hookFileKind reads lstat: a symbolic link, a hard link and a non-regular file are not files; ENOENT is absent; any other failure is other', () => {
    const st = (o: { link?: boolean; file?: boolean; nlink?: number }) => () => ({
      isSymbolicLink: () => o.link === true, isFile: () => o.file !== false, nlink: o.nlink ?? 1,
    })
    expect(hookFileKind(st({}))).toBe('file')
    expect(hookFileKind(st({ link: true, file: false }))).toBe('link')
    expect(hookFileKind(st({ nlink: 2 }))).toBe('link')
    expect(hookFileKind(st({ file: false }))).toBe('other')
    const fails = (e: unknown) => () => { throw e }
    expect(hookFileKind(fails(Object.assign(new Error('ENOENT'), { code: 'ENOENT' })))).toBe('absent')
    expect(hookFileKind(fails(Object.assign(new Error('ENOTDIR'), { code: 'ENOTDIR' })))).toBe('other')
    expect(hookFileKind(fails(Object.assign(new Error('EACCES'), { code: 'EACCES' })))).toBe('other')
    expect(hookFileKind(fails(null))).toBe('other')
  })
})

// M1: the node the hook is baked with is a full path, found through PATH folders that are full paths.
describe('shieldNodePath', () => {
  const seen: NodeJS.ProcessEnv[] = []
  const resolveWith = (answer: string) => (env: NodeJS.ProcessEnv): string => { seen.push(env); return answer }

  it('hands the resolver only the PATH folders written as full paths', () => {
    seen.length = 0
    expect(shieldNodePath({ PATH: 'tools:/usr/bin: :./bin:/opt/node/bin', HOME: '/h' }, resolveWith('/usr/bin/node'), posix, ':')).toBe('/usr/bin/node')
    expect(seen[0].PATH).toBe('/usr/bin:/opt/node/bin')
    expect(seen[0].HOME).toBe('/h')
    expect(seen[0].Path).toBeUndefined()
    seen.length = 0
    shieldNodePath({ Path: 'tools;C:\\Program Files\\nodejs;.' }, resolveWith('C:\\Program Files\\nodejs\\node.exe'), win32, ';')
    expect(seen[0].PATH).toBe('C:\\Program Files\\nodejs')
    seen.length = 0
    shieldNodePath({}, resolveWith('/usr/local/bin/node'), posix, ':')
    expect(seen[0].PATH).toBe('')
  })

  it('is null when the resolver finds no node and falls back to the bare name, or answers a relative path', () => {
    expect(shieldNodePath({ PATH: '/usr/bin' }, resolveWith('node'), posix, ':')).toBeNull()
    expect(shieldNodePath({ PATH: '/usr/bin' }, resolveWith('tools/node'), posix, ':')).toBeNull()
  })
})

describe('hookStatus', () => {
  it('reports absent for an empty hooks dir', () => {
    const fs = fakeFs()
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'absent', 'pre-push': 'absent' })
  })

  it('reports installed after install', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'installed', 'pre-push': 'installed' })
  })

  // HOLD-A R2-3: status reads a hook file the way uninstallHooks does (readHook): never through a link and never one
  // that is not a regular file. So 'installed' is always a shield Remove protection can take out.
  it('reports a linked hook and one that is not a regular file by their kind, without reading them, as uninstall leaves them', () => {
    const mine = fakeFs()
    installHooks(PATHS, mine.deps)
    const fs = fakeFs(
      { [PRE_COMMIT]: mine.files.get(PRE_COMMIT)!, [PRE_PUSH]: mine.files.get(PRE_PUSH)! },
      { [PRE_COMMIT]: 'link', [PRE_PUSH]: 'other' },
    )
    const readFile = vi.spyOn(fs.deps, 'readFile')
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'link', 'pre-push': 'other' })
    expect(readFile).not.toHaveBeenCalled()
    expect(uninstallHooks(PATHS, fs.deps)).toEqual([])
    expect(fs.removed).toEqual([])
    expect(fs.wrote).toEqual([])
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'link', 'pre-push': 'other' })
  })

  it('reports a link that leads nowhere as a link, not as absent', () => {
    const fs = fakeFs({}, { [PRE_COMMIT]: 'link' })
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'link', 'pre-push': 'absent' })
  })

  it('reports foreign for a hook that is not ours, per hook', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'foreign', 'pre-push': 'absent' })
  })

  it('reports installed for a chained hook (our block is present)', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)['pre-commit']).toBe('installed')
  })

  it('goes back to foreign after uninstalling a chained hook', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    installHooks(PATHS, fs.deps)
    uninstallHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)['pre-commit']).toBe('foreign')
  })

  it('stays foreign for a non-shell hook we refused to install into', () => {
    const fs = fakeFs({ [PRE_COMMIT]: PYTHON_HOOK })
    installHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)['pre-commit']).toBe('foreign')
  })

  it('survives an unreadable hook file without throwing', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY })
    const deps: HookDeps = { ...fs.deps, readFile: () => null }
    expect(hookStatus(PATHS, deps)['pre-commit']).toBe('foreign')
  })

  // HOLD-B (hold-a-review re-review 1): a block of ours that is not the one Protect writes now is 'outdated', not
  // 'installed', so the person is told to protect the repository again. Protect again replaces it, in place.
  const OLD_BLOCK = [BEGIN, 'command -v node >/dev/null 2>&1 || exit 0', 'node "/old/termpolis-githook.cjs" pre-commit || exit 1', END, ''].join('\n')

  it('reports outdated for a block an older Termpolis wrote (node looked up on PATH), and installed once protected again', () => {
    const fs = fakeFs({ [PRE_COMMIT]: `#!/bin/sh\n${OLD_BLOCK}` })
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'outdated', 'pre-push': 'absent' })
    installHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'installed', 'pre-push': 'installed' })
  })

  it('reports outdated for an old block chained into a foreign hook, and protecting again keeps the foreign lines', () => {
    const fs = fakeFs({ [PRE_COMMIT]: HUSKY.replace('\n', `\n${OLD_BLOCK}`) })
    expect(hookStatus(PATHS, fs.deps)['pre-commit']).toBe('outdated')
    installHooks(PATHS, fs.deps)
    expect(hookStatus(PATHS, fs.deps)['pre-commit']).toBe('installed')
    expect(fs.files.get(PRE_COMMIT)).toContain('npx lint-staged || exit 1')
    expect(fs.files.get(PRE_COMMIT)).not.toContain('command -v node')
  })

  it('reports outdated when node or the scanner moved since the block was written', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    expect(hookStatus({ ...PATHS, nodePath: 'C:\\Users\\me\\nvm\\v24\\node.exe' }, fs.deps)['pre-push']).toBe('outdated')
    expect(hookStatus({ ...PATHS, scriptPath: 'D:\\Termpolis\\termpolis-githook.cjs' }, fs.deps)['pre-commit']).toBe('outdated')
  })

  it('reports outdated for a doubled block and for a block whose lines gained CRs (sh would choke on them)', () => {
    const fs = fakeFs()
    installHooks(PATHS, fs.deps)
    const ours = fs.files.get(PRE_COMMIT)!
    fs.files.set(PRE_COMMIT, ours + ours.slice('#!/bin/sh\n'.length))
    fs.files.set(PRE_PUSH, fs.files.get(PRE_PUSH)!.replace(/\n/g, '\r\n'))
    expect(hookStatus(PATHS, fs.deps)).toEqual({ 'pre-commit': 'outdated', 'pre-push': 'outdated' })
  })

  it('stays installed when Termpolis finds no node now (Protect would refuse) and for a block in a hook Protect skips', () => {
    const fs = fakeFs({ [PRE_COMMIT]: `#!/bin/sh\n${OLD_BLOCK}`, [PRE_PUSH]: `${PYTHON_HOOK}${OLD_BLOCK}` })
    expect(hookStatus({ ...PATHS, nodePath: '' }, fs.deps)).toEqual({ 'pre-commit': 'installed', 'pre-push': 'installed' })
    expect(hookStatus(PATHS, fs.deps)['pre-push']).toBe('installed')
  })
})

// #36 (WPS M7). `rev-parse --git-path hooks` answers with core.hooksPath, and a repository's own config can point that
// anywhere, so "Protect a repository" would write pre-commit and pre-push outside it. The installer writes only into
// the repository's git folder or working tree, after following links, unless core.hooksPath is the person's own.
describe('Commit Shield hooks — where the installer may write (#36)', () => {
  const noLinks = async (p: string): Promise<string> => p
  const facts = (hooksDir: string, roots: string[], scopes: string[] | null, over: Partial<HooksWriteFacts> = {}) =>
    shieldMayWriteHooks({ hooksDir, roots, scopes: async () => scopes, path: posix, platform: 'linux', realpath: noLinks, ...over })

  it('allows the git folder, a folder inside it, and a folder in the working tree (husky)', async () => {
    expect(await facts('/repo/.git/hooks', ['/repo/.git', '/repo'], ['local'])).toBe(true)
    expect(await facts('/repo/.git', ['/repo/.git', '/repo'], ['local'])).toBe(true)
    expect(await facts('/repo/.husky', ['/repo/.git', '/repo'], ['local'])).toBe(true)
    expect(await facts('/repo/..hooks', ['/repo'], ['local'])).toBe(true) // a name that starts with two dots is inside
    // A linked worktree: its hooks live in the main repository's git folder, its common dir.
    expect(await facts('/main/.git/hooks', ['/main/.git', '/wt'], null)).toBe(true)
  })

  it("refuses a folder outside the repository that the repository's own config names", async () => {
    expect(await facts('/elsewhere', ['/repo/.git', '/repo'], ['local', 'command'])).toBe(false)
    expect(await facts('/elsewhere', ['/repo/.git', '/repo'], ['worktree'])).toBe(false)
    expect(await facts('/elsewhere', ['/repo/.git', '/repo'], ['global', 'local'])).toBe(false) // the local one wins
    expect(await facts('/repo-evil/hooks', ['/repo/.git', '/repo'], ['local'])).toBe(false) // a prefix is not inside
    expect(await facts('/', ['/repo'], ['local'])).toBe(false) // the parent is not inside
    expect(await facts('/elsewhere', [], ['local'])).toBe(false)
  })

  it("allows a folder outside it only when core.hooksPath is the person's own (global or system)", async () => {
    expect(await facts('/home/me/.githooks', ['/repo/.git', '/repo'], ['global', 'command'])).toBe(true)
    expect(await facts('/etc/githooks', ['/repo/.git', '/repo'], ['system'])).toBe(true)
    // Only the app's own command-line setting, unread, or read as nothing: refused.
    expect(await facts('/home/me/.githooks', ['/repo/.git', '/repo'], ['command'])).toBe(false)
    expect(await facts('/home/me/.githooks', ['/repo/.git', '/repo'], null)).toBe(false)
    expect(await facts('/home/me/.githooks', ['/repo/.git', '/repo'], [])).toBe(false)
  })

  it('asks for the scopes only when the folder is outside the repository', async () => {
    let asked = 0
    const scopes = async (): Promise<string[] | null> => { asked++; return ['global'] }
    await shieldMayWriteHooks({ hooksDir: '/repo/.git/hooks', roots: ['/repo/.git'], scopes, path: posix, platform: 'linux', realpath: noLinks })
    expect(asked).toBe(0)
    await shieldMayWriteHooks({ hooksDir: '/x', roots: ['/repo/.git'], scopes, path: posix, platform: 'linux', realpath: noLinks })
    expect(asked).toBe(1)
  })

  it('ignores case and slash direction on Windows, case on macOS, and neither on Linux', async () => {
    expect(await facts('C:\\Repo\\.git\\hooks', ['c:/repo/.git/'], ['local'], { path: win32, platform: 'win32' })).toBe(true)
    expect(await facts('D:\\repo\\.git\\hooks', ['C:\\repo\\.git'], ['local'], { path: win32, platform: 'win32' })).toBe(false) // another drive
    expect(await facts('/Users/me/Repo/.git/hooks', ['/Users/me/repo/.git'], ['local'], { platform: 'darwin' })).toBe(true)
    expect(await facts('/home/me/Repo/.git/hooks', ['/home/me/repo/.git'], ['local'])).toBe(false)
  })

  it('follows links: a folder in the repository that leads outside is outside, and the reverse is inside', async () => {
    const links: Record<string, string> = { '/repo/hooks-link': '/elsewhere', '/link/repo': '/real/repo' }
    const real = new Set(['/', '/repo', '/real', '/real/repo', '/real/repo/.git'])
    // Only what exists resolves; a hooks folder may not exist yet (the installer creates it).
    const realpath = async (p: string): Promise<string> => {
      if (p in links) return links[p]
      if (real.has(p)) return p
      throw Object.assign(new Error('ENOENT'), { code: 'ENOENT' })
    }
    expect(await facts('/repo/hooks-link/pre', ['/repo/.git', '/repo'], ['local'], { realpath })).toBe(false)
    expect(await facts('/link/repo/.git/hooks', ['/real/repo/.git'], ['local'], { realpath })).toBe(true)
  })

  it('a realpath that always fails compares the paths as written', async () => {
    const realpath = async (): Promise<string> => { throw new Error('EACCES') }
    expect(await facts('/repo/.git/hooks', ['/repo/.git'], ['local'], { realpath })).toBe(true)
    expect(await facts('/elsewhere', ['/repo/.git'], ['local'], { realpath })).toBe(false)
  })

  it('hooksPathScopes reads the scope of every value from `git config --show-scope -z --get-all`', () => {
    // Measured on git 2.5x: a repository value, then the app's own `-c core.hooksPath=NUL` read prefix.
    expect(hooksPathScopes('local\0../../elsewhere\0command\0NUL\0')).toEqual(['local', 'command'])
    expect(hooksPathScopes('global\0/home/me/.githooks\0')).toEqual(['global'])
    expect(hooksPathScopes('')).toEqual([])
  })

  it('shieldHooksAllowed asks git for the common dir, the top level and the scopes, through the runner given', async () => {
    const asked: string[] = []
    const answers: Record<string, string | Error> = {
      'rev-parse --git-common-dir': '.git\n',
      'rev-parse --show-toplevel': '/repo\n',
      'config --show-scope -z --get-all core.hooksPath': 'local\0../elsewhere\0',
    }
    const git = async (args: string[]): Promise<string> => {
      const k = args.join(' ')
      asked.push(k)
      const a = answers[k]
      if (a instanceof Error) throw a
      return a
    }
    const base = { path: posix, platform: 'linux' as NodeJS.Platform, realpath: noLinks, readFile: async () => null }
    expect(await shieldHooksAllowed({ repo: '/repo', hooksDir: '/repo/.git/hooks', git, ...base })).toBe(true)
    expect(asked).toEqual(['rev-parse --show-toplevel', 'rev-parse --git-common-dir'])
    expect(await shieldHooksAllowed({ repo: '/repo', hooksDir: '/elsewhere', git, ...base })).toBe(false)
    answers['config --show-scope -z --get-all core.hooksPath'] = 'global\0/elsewhere\0'
    expect(await shieldHooksAllowed({ repo: '/repo', hooksDir: '/elsewhere', git, ...base })).toBe(true)
    // A bare repository has no top level; its hooks are in the folder itself.
    answers['rev-parse --show-toplevel'] = new Error('fatal: this operation must be run in a work tree')
    answers['rev-parse --git-common-dir'] = '.\n'
    answers['rev-parse --absolute-git-dir'] = '/repo.git\n'
    expect(await shieldHooksAllowed({ repo: '/repo.git', hooksDir: '/repo.git/hooks', git, ...base })).toBe(true)
    // A git that cannot read the scopes refuses the outside folder.
    answers['config --show-scope -z --get-all core.hooksPath'] = new Error('error: unknown option `show-scope\'')
    expect(await shieldHooksAllowed({ repo: '/repo', hooksDir: '/elsewhere', git, ...base })).toBe(false)
    // An empty answer names no folder: nothing is inside.
    answers['rev-parse --git-common-dir'] = '  \n'
    expect(await shieldHooksAllowed({ repo: '/repo', hooksDir: '/repo/.git/hooks', git, ...base })).toBe(false)
  })

  it('shieldHooksAllowed takes a git folder outside the working tree only when its worktree link is read back (M2)', async () => {
    const answers: Record<string, string | Error> = {
      'rev-parse --show-toplevel': '/repo\n',
      'rev-parse --git-common-dir': '/main/.git\n',
      'rev-parse --absolute-git-dir': '/main/.git/worktrees/w\n',
      'config --show-scope -z --get-all core.hooksPath': '',
    }
    const git = async (args: string[]): Promise<string> => {
      const a = answers[args.join(' ')]
      if (a instanceof Error) throw a
      return a
    }
    let gitdirFile: string | null = '/repo/.git\n'
    const readFile = vi.fn(async () => gitdirFile)
    const o = { repo: '/repo', hooksDir: '/main/.git/hooks', git, readFile, path: posix, platform: 'linux' as NodeJS.Platform, realpath: noLinks }
    // A linked worktree whose gitdir file names this working tree's .git: its main repository's hooks are its own.
    expect(await shieldHooksAllowed(o)).toBe(true)
    expect(readFile).toHaveBeenCalledWith('/main/.git/worktrees/w/gitdir')
    // A gitdir file that can't be read names nothing.
    gitdirFile = null
    expect(await shieldHooksAllowed(o)).toBe(false)
    // A git that names no git dir leaves the outside folder out.
    gitdirFile = '/repo/.git\n'
    answers['rev-parse --absolute-git-dir'] = new Error('fatal: not a git repository')
    expect(await shieldHooksAllowed(o)).toBe(false)
  })

  // HOLD-A N2: a refusal says which kind it is, so the person is told the right reason.
  it('shieldHooksVerdict tells a git folder kept outside the working folder from a core.hooksPath refusal', async () => {
    const answers: Record<string, string | Error> = {
      'rev-parse --show-toplevel': '/repo\n',
      'rev-parse --git-common-dir': '/sep/repo.git\n',
      'rev-parse --absolute-git-dir': '/sep/repo.git\n',
      'config --local --get core.worktree': new Error(''),
      'config --show-scope -z --get-all core.hooksPath': '',
    }
    const git = async (args: string[]): Promise<string> => {
      const a = answers[args.join(' ')]
      if (a instanceof Error) throw a
      return a ?? ''
    }
    const base = { repo: '/repo', git, readFile: async () => null, path: posix, platform: 'linux' as NodeJS.Platform, realpath: noLinks }
    // `git init --separate-git-dir`: the hooks are in a git folder the shield can't tell is this repository's.
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/sep/repo.git/hooks' })).toBe('gitDirOutside')
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/sep/repo.git' })).toBe('gitDirOutside')
    expect(await shieldHooksAllowed({ ...base, hooksDir: '/sep/repo.git/hooks' })).toBe(false)
    // The same repository's own core.hooksPath pointing anywhere else is the hooksPath refusal.
    answers['config --show-scope -z --get-all core.hooksPath'] = 'local\0/elsewhere\0'
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/elsewhere' })).toBe('hooksPath')
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/sep/repo.git-evil/hooks' })).toBe('hooksPath')
    // A git folder that belongs (here, inside the working tree) is a root, so a refusal there is never this kind.
    answers['rev-parse --git-common-dir'] = '.git\n'
    answers['rev-parse --absolute-git-dir'] = '/repo/.git\n'
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/repo/.git/hooks' })).toBe('allowed')
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/elsewhere' })).toBe('hooksPath')
    // A git that names no git folder, or no working tree (a bare repository it refuses), keeps the old words.
    answers['rev-parse --git-common-dir'] = ''
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/sep/repo.git/hooks' })).toBe('hooksPath')
    answers['rev-parse --show-toplevel'] = new Error('fatal: this operation must be run in a work tree')
    answers['rev-parse --git-common-dir'] = '/sep/repo.git\n'
    answers['rev-parse --absolute-git-dir'] = '/sep/repo.git\n'
    expect(await shieldHooksVerdict({ ...base, hooksDir: '/sep/repo.git/hooks' })).toBe('hooksPath')
  })
})
