// Synthetic Claude Code transcript lines for the reflect-pass tests. Nothing here is real data: every
// string is made up, and secret-looking samples (there are none) would use the repeat trick.

import { PRIMER_CLOSE, PRIMER_OPEN, PRIMER_PREFACE, delegationHeader } from '../../src/shared/headlessPrompt'

const TS = '2026-11-03T10:00:00.000Z'

/** A user turn whose content is a plain string. */
export const userLine = (text: string, extra: Record<string, unknown> = {}): string =>
  JSON.stringify({ type: 'user', message: { role: 'user', content: text }, timestamp: TS, sessionId: 'sess-1', cwd: '/r', ...extra })

/** A user turn whose content is an array of blocks (an attachment plus text, say). */
export const userBlocksLine = (text: string): string =>
  JSON.stringify({ type: 'user', message: { role: 'user', content: [{ type: 'text', text }] }, timestamp: TS, sessionId: 'sess-1' })

/** An assistant turn: text plus a tool call (the tool call is not dialogue). */
export const assistantLine = (text: string): string =>
  JSON.stringify({
    type: 'assistant',
    message: { role: 'assistant', content: [{ type: 'text', text }, { type: 'tool_use', id: 't1', name: 'Read', input: { file_path: '/x' } }] },
    timestamp: TS,
    sessionId: 'sess-1',
  })

/** An assistant turn that only calls a tool: no dialogue text, so no turn. */
export const toolCallLine = (): string =>
  JSON.stringify({ type: 'assistant', message: { role: 'assistant', content: [{ type: 'tool_use', id: 't2', name: 'Bash', input: { command: 'ls' } }] }, timestamp: TS })

/** The user turn that returns a tool's result: no dialogue text either. */
export const toolResultLine = (): string =>
  JSON.stringify({ type: 'user', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't2', content: 'a.txt' }] }, timestamp: TS })

export const metaLine = (): string => userLine('Caveat: generated by the harness', { isMeta: true })
export const noiseLine = (): string => userLine('<command-name>/clear</command-name>')
export const summaryLine = (): string => JSON.stringify({ type: 'summary', summary: 'compacted', leafUuid: 'u1' })

/** A line a writer has not finished (or garbage): not JSON, no turn, and never an error. */
export const BROKEN_LINE = '{"type":"user","message":{"role":"user","content":"never closed'

export const PREAMBLE = '<environment_context>cwd: /r</environment_context>'

/** The opening prompt of a local headless run: memory primer first, then the task. */
export const primed = (task: string): string =>
  [PRIMER_OPEN, ...PRIMER_PREFACE, '', '- [claude · 2d ago] the parser lives in src/parse.ts', PRIMER_CLOSE, '', task].join('\n')

/** The opening prompt of a job another computer ran here over Linked machines. */
export const delegated = (task = 'Review the parser.'): string => `${delegationHeader('laptop', '/home/me/repo')}\n\n${task}`

/** Lines joined the way a transcript is written: each ends with a newline. */
export const lines = (...ls: string[]): string => ls.join('\n') + '\n'

/** A small deterministic PRNG, so a failing seed can be replayed. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

