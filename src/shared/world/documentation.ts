// The Lumopolis documentation model: a sanitised WorldDoc turned into plain data (sections of paragraphs, claims,
// lists and tables) that documentationHtml.ts renders. It states only what the world records, and every sentence a
// card also shows comes from the same cardFacts helper, so the document and the cards cannot disagree. The model
// holds plain text: escaping is the renderer's job. Pure, ES2020, and deterministic (the date is passed in).
import {
  AI_NAME, BUILD_STATUS_TEXT, CARD_HEADINGS, FLOOR_CAP, NOT_DESCRIBED, NO_WHY_YET, allEdges, direction, edgeFromCode,
  evidenceText, nodeName, notInDesign, runsIn, serviceNamesLine, sizeNote
} from './cardFacts'
import { edgeItems, edgeSummary } from './edgeText'
import { NOT_IN_DESIGN } from './reconcile'
import type { Building, Claim, ClaimState, WorldDoc, WorldEdge } from './types'

export type DocBlock =
  | { kind: 'p'; text: string }
  | { kind: 'claims'; items: { text: string; state: ClaimState; refs: string[] }[] }
  | { kind: 'list'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][] }
  | { kind: 'map' }
  | { kind: 'picture' }
export interface DocSection { id: string; title: string; blocks: DocBlock[]; children?: DocSection[] }
export interface DocModel { title: string; subtitle: string; design: boolean; sections: DocSection[] }
/** `title` is the project's name as the person typed it; `generatedOn` is passed in so the output is deterministic. */
export interface DocOptions { title: string; picture: boolean; generatedOn: string }

export const SECTION_IDS = ['title', 'coverage', 'overview', 'glance', 'runs', 'areas', 'connections', 'flows', 'outside', 'planVsBuilt', 'planned', 'glossary', 'notCovered'] as const

/** The title block's source line, verbatim from the design spec (§5.4). */
export const FROM_CODE = 'Generated by Termpolis Lumopolis from the code'
export const FROM_DESIGN = 'Generated from the design'
/** What each claim state means, after the coverage sentence; a design world adds PROPOSED_MEANS. */
export const STATES_MEAN = 'Statements marked *inferred* come from reading the code, *verified* from tests or a person, *observed* from the code itself.'
export const PROPOSED_MEANS = 'Statements marked *proposed* come from the design.'
/** The mark on an outside system the code does not show directly (it is in fog). */
export const NOT_SEEN_IN_CODE = 'not seen in code'
/** What no Lumopolis world records, closing the "doesn't cover yet" section. */
export const NOT_SEEN = 'Lumopolis reads the code, not the running app: it does not see runtime behaviour or data contents.'
/** The Connections table's columns: every field of the line card. */
export const CONNECTION_HEAD = ['From', 'To', CARD_HEADINGS.travels, 'How', CARD_HEADINGS.direction, 'Why', CARD_HEADINGS.howOften]

const p = (text: string): DocBlock => ({ kind: 'p', text })
const list = (items: string[]): DocBlock => ({ kind: 'list', items })
const section = (id: string, title: string, blocks: DocBlock[], children: DocSection[] = []): DocSection =>
  (children.length ? { id, title, blocks, children } : { id, title, blocks })
const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`
const claimBlock = (claims: Claim[]): DocBlock =>
  ({ kind: 'claims', items: claims.map((c) => ({ text: c.text, state: c.state, refs: c.evidence.map(evidenceText) })) })
/** Claims as the line card's plain text has them: "text [state]", one after another. */
const claimText = (claims: Claim[]): string => claims.map((c) => `${c.text} [${c.state}]`).join(' ')

/** The world's facts each section reads, worked out once. */
interface Ctx { doc: WorldDoc; design: boolean; project: string; edges: WorldEdge[] }

function titleSection(c: Ctx, title: string, opts: DocOptions): DocSection {
  const { head, dirty } = c.doc.sourceRevision
  return section('title', title, [
    p(c.design ? FROM_DESIGN : FROM_CODE),
    p(`Project: ${c.project}`),
    p(`Generated on ${opts.generatedOn}`),
    ...(head ? [p(`Commit ${head}${dirty ? ', with changes not yet committed' : ''}`)] : [])
  ])
}

function coverage(c: Ctx): DocSection {
  const parts = c.doc.buildings.filter((b) => b.how.length > 0).length
  const lines = c.doc.edges.filter((e) => e.how.length > 0).length
  return section('coverage', 'Coverage', [
    p(`${parts} of ${c.doc.buildings.length} parts and ${lines} of ${c.doc.edges.length} connections are described.`),
    p(STATES_MEAN),
    ...(c.design ? [p(PROPOSED_MEANS)] : [])
  ])
}

function overview(c: Ctx): DocSection {
  const { doc, design } = c
  const procs = Object.keys(doc.processes).map((k) => doc.processes[k].label)
  const stack = Array.from(new Set(doc.buildings.flatMap((b) => b.stack))).sort()
  const blocks = [p(`${c.project} ${design ? 'will have' : 'has'} ${plural(doc.districts.length, 'area', 'areas')}, ${plural(doc.buildings.length, 'part', 'parts')} and ${plural(doc.edges.length, 'connection', 'connections')}.`)]
  if (procs.length) blocks.push(p(`It ${design ? 'will run' : 'runs'} as ${plural(procs.length, 'process', 'processes')}: ${procs.join(', ')}.`))
  if (stack.length) blocks.push(p(`It ${design ? 'will be' : 'is'} built with ${stack.join(', ')}.`))
  if (doc.districts.length) blocks.push(list(doc.districts.map((d) => (d.subtitle ? `${d.name}: ${d.subtitle}` : d.name))))
  return section('overview', 'Overview', blocks)
}

function runs(c: Ctx): DocSection {
  const keys = Object.keys(c.doc.processes)
  if (keys.length === 0) return section('runs', 'How it runs', [p(c.design ? 'The design names no processes.' : 'The code shows no processes.')])
  const items = keys.map((k) => {
    const names = c.doc.buildings.filter((b) => b.process === k).map((b) => b.name)
    const label = c.doc.processes[k].label
    return names.length ? `${label}: ${names.join(', ')}` : label
  })
  return section('runs', 'How it runs', [
    p(c.design ? 'Each planned process and the parts that will run in it.' : 'Each process and the parts that run in it.'), list(items)
  ])
}

/** A line as a card lists it under What comes in / What goes out, with its direction sentence. */
const edgeItem = (c: Ctx, e: WorldEdge, dir: 'from' | 'to'): string =>
  `${edgeSummary(e.label)} ${dir} ${nodeName(c.doc, e[dir])}: ${direction(c.doc, e).text}`

/** A floor as "name · tech: members", its members capped at FLOOR_CAP with "and N more". */
function floorItem(f: Building['floors'][number]): string {
  const tech = f.tech.length ? ` · ${f.tech.join(', ')}` : ''
  const shown = f.members.slice(0, FLOOR_CAP).join(', ')
  const more = f.members.length > FLOOR_CAP ? ` and ${f.members.length - FLOOR_CAP} more` : ''
  return `${f.name}${tech}${shown ? `: ${shown}${more}` : ''}`
}

/** A part as its card shows it (renderer engine cards.ts buildingCard), in the card's order under its headings. */
function part(c: Ctx, b: Building): DocSection {
  const { doc } = c
  const heads: DocSection[] = []
  const add = (key: keyof typeof CARD_HEADINGS, blocks: DocBlock[]): void => {
    heads.push(section(`part:${b.id}:${key}`, CARD_HEADINGS[key], blocks))
  }
  const described = (claims: Claim[]): DocBlock[] => [claims.length ? claimBlock(claims) : p(NOT_DESCRIBED)]
  add('whatItDoes', described(b.how))
  if (b.floors.length) {
    const floors = b.floors.slice(0, FLOOR_CAP).map(floorItem)
    if (b.floors.length > FLOOR_CAP) floors.push(`and ${b.floors.length - FLOOR_CAP} more`)
    add('inside', [list(floors)])
  }
  const big = sizeNote(doc, b, 'listed')
  if (big) add('whyBig', [p(big)])
  if (b.stack.length) add('technology', [list(b.stack.map((t) => (doc.glossary[t] ? `${t}: ${doc.glossary[t]}` : t)))])
  add('whyBuilt', described(b.why))
  const names = serviceNamesLine(doc, b.id)
  if (names !== null) add('serviceNames', [p(names)])
  if (b.claims.length) add('know', [claimBlock(b.claims)])
  const ins = c.edges.filter((e) => e.to === b.id)
  const outs = c.edges.filter((e) => e.from === b.id)
  if (ins.length) add('comesIn', [list(ins.map((e) => edgeItem(c, e, 'from')))])
  if (outs.length) add('goesOut', [list(outs.map((e) => edgeItem(c, e, 'to')))])
  const run = runsIn(doc, b)
  const head = [
    ...(b.techLabel ? [p(b.techLabel)] : []),
    p(`Status: ${BUILD_STATUS_TEXT[b.status]}${notInDesign(doc, b.id) ? `; ${NOT_IN_DESIGN}` : ''}`),
    ...(run.trim() ? [p(`Runs in: ${run}`)] : [])
  ]
  return section(`part:${b.id}`, b.nameState === 'inferred' ? `${b.name} ${AI_NAME}` : b.name, head, heads)
}

function areas(c: Ctx): DocSection {
  if (c.doc.districts.length === 0) return section('areas', 'Areas', [p('There are no areas yet.')])
  return section('areas', 'Areas', [], c.doc.districts.map((d) => section(
    `area:${d.id}`, d.name, d.subtitle ? [p(d.subtitle)] : [], c.doc.buildings.filter((b) => b.districtId === d.id).map((b) => part(c, b))
  )))
}

/** One row of the Connections table: every field the line card shows. */
function connection(c: Ctx, e: WorldEdge): string[] {
  const { doc } = c
  const cargo = doc.cargo[e.cargo]
  const carried = (edgeItems(e.label) ?? [e.label]).join(', ')
  const travels = [cargo ? cargo.label : e.cargo, carried].filter((s) => s.trim() !== '').join(': ')
  const how = [
    e.how.length ? claimText(e.how) : edgeFromCode(doc, e),
    ...(e.tech.length ? [`${CARD_HEADINGS.technology}: ${e.tech.join(', ')}`] : []),
    ...(e.claims.length ? [`${CARD_HEADINGS.know}: ${claimText(e.claims)}`] : [])
  ].join(' ')
  return [nodeName(doc, e.from), nodeName(doc, e.to), travels, how, direction(doc, e).text, e.why.length ? claimText(e.why) : NO_WHY_YET, e.rate]
}

/** A tour step's id in words: an area's name, a line's two ends, else the part's name. */
function stepName(c: Ctx, id: string): string {
  const d = c.doc.districts.find((x) => x.id === id)
  if (d) return d.name
  const e = c.edges.find((x) => x.id === id)
  return e ? `${nodeName(c.doc, e.from)} → ${nodeName(c.doc, e.to)}` : nodeName(c.doc, id)
}

function flows(c: Ctx): DocSection {
  if (c.doc.tours.length === 0) return section('flows', 'Main flows', [p('No tours are recorded yet.')])
  return section('flows', 'Main flows', [], c.doc.tours.map((t) => section(`flow:${t.id}`, t.title, [list(t.steps.map((s, i) => {
    const involved = s.ids.map((id) => stepName(c, id))
    return `${i + 1}. ${s.caption}${involved.length ? ` (${involved.join(', ')})` : ''}`
  }))])))
}

function outside(c: Ctx): DocSection {
  if (c.doc.externals.length === 0) return section('outside', 'Outside systems', [p('No outside systems are recorded.')])
  const rows = c.doc.externals.map((x) => {
    const by = Array.from(new Set(c.edges.filter((e) => e.to === x.id).map((e) => nodeName(c.doc, e.from))))
    return [x.fog ? `${x.name} (${NOT_SEEN_IN_CODE})` : x.name, x.kind, by.join(', ')]
  })
  return section('outside', 'Outside systems', [{ kind: 'table', head: ['Name', CARD_HEADINGS.whatItIs, 'Reached by'], rows }])
}

/** Plan vs built, one child per linked design; null when the project has none. */
function planVsBuilt(c: Ctx): DocSection | null {
  const names = (ids: string[]): string => (ids.length ? ids.map((id) => nodeName(c.doc, id)).join(', ') : 'none')
  const linked = c.doc.layers.plan.flatMap((pl) => {
    const r = pl.reconcile
    return r ? [section(`reconcile:${pl.id}`, pl.title, [
      p(`Matched: ${names(Object.keys(r.matched).map((k) => r.matched[k]))}`),
      p(`Missing (planned, not built yet): ${names(r.missing)}`),
      p(`Extra (built, not in the design): ${names(r.extra)}`),
      p(`Changed (built, still short of the design): ${names(r.changed)}`)
    ])] : []
  })
  return linked.length ? section('planVsBuilt', 'Plan vs built', [], linked) : null
}

function planned(c: Ctx): DocSection {
  if (c.doc.layers.plan.length === 0) return section('planned', 'Planned changes', [p('No planned changes are recorded.')])
  return section('planned', 'Planned changes', [], c.doc.layers.plan.map((pl) => {
    const removes = pl.removes ?? []
    return section(`plan:${pl.id}`, pl.title, [
      ...(pl.summary.length ? [claimBlock(pl.summary)] : []),
      ...(pl.buildings.length ? [p(`Adds: ${pl.buildings.map((b) => b.name).join(', ')}`)] : []),
      ...(removes.length ? [p(`Removes: ${removes.map((id) => nodeName(c.doc, id)).join(', ')}`)] : [])
    ])
  }))
}

function glossary(c: Ctx): DocSection {
  const terms = Object.keys(c.doc.glossary).sort()
  if (terms.length === 0) return section('glossary', 'Glossary', [p('The world has no glossary yet.')])
  return section('glossary', 'Glossary', [{ kind: 'table', head: ['Term', 'Meaning'], rows: terms.map((t) => [t, c.doc.glossary[t]]) }])
}

function notCovered(c: Ctx): DocSection {
  const { doc } = c
  const parts = doc.buildings.filter((b) => b.how.length === 0)
  const lines = doc.edges.filter((e) => e.how.length === 0)
  const blocks: DocBlock[] = []
  if (parts.length) blocks.push(p('These parts are not described yet:'), list(parts.map((b) => b.name)))
  if (lines.length) {
    blocks.push(p('These connections are not described yet:'),
      list(lines.map((e) => `${edgeSummary(e.label)} (${nodeName(doc, e.from)} → ${nodeName(doc, e.to)})`)))
  }
  if (blocks.length === 0) {
    blocks.push(p(doc.buildings.length + doc.edges.length ? 'Every part and connection is described.' : 'The world has no parts or connections yet.'))
  }
  blocks.push(p(NOT_SEEN))
  return section('notCovered', "What this document doesn't cover yet", blocks)
}

/**
 * The documentation of a world: a code world's "How <Project> works" or a design world's "<Project>: application
 * plan", in SECTION_IDS order (Plan vs built only when a design is linked). The caller sanitises the world first
 * (exportSanitize.ts); this only reads it.
 */
export function buildDocumentation(doc: WorldDoc, opts: DocOptions): DocModel {
  const design = doc.projectKey.startsWith('design:')
  const project = opts.title.trim() || 'this project'
  const c: Ctx = { doc, design, project, edges: allEdges(doc) }
  const title = design ? `${project}: application plan` : `How ${project} works`
  const vs = planVsBuilt(c)
  const sections = [
    titleSection(c, title, opts), coverage(c), overview(c),
    section('glance', 'The city at a glance', [...(opts.picture ? [{ kind: 'picture' } as DocBlock] : []), { kind: 'map' }]),
    runs(c), areas(c),
    section('connections', 'Connections', [{ kind: 'table', head: [...CONNECTION_HEAD], rows: doc.edges.map((e) => connection(c, e)) }]),
    flows(c), outside(c), ...(vs ? [vs] : []), planned(c), glossary(c), notCovered(c)
  ]
  return { title, subtitle: design ? FROM_DESIGN : FROM_CODE, design, sections }
}
